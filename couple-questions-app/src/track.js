// Шаги воронки.
//
// Вопрос, на который эта таблица отвечает: где человек останавливается.
// Тридцать открыли приглашение — сколько ответило на первый вопрос?
// Сколько дошло до экрана оплаты? Сколько закрыло тему целиком? Без
// этого мы узнаём про продукт только то, что кто-то расскажет словами.
//
// Чего здесь нет и не будет: текстов ответов, имён, содержимого связей.
// Только название шага и числа рядом с ним. По событию видно «человек
// закрыл тему про деньги», но не видно, что он про них написал.
import { isRemote, supabase } from "./backend.js";

/** Названия шагов. Список закрытый: случайные строки ломают отчёты. */
export const STEP = {
  open: "открыл приложение",
  onboarded: "прошёл знакомство",
  invitedOpen: "открыл приглашение",
  inviteMade: "создал приглашение",
  paired: "связь состоялась",
  answered: "ответил на вопрос",
  blockDone: "закрыл тему",
  verdictAsked: "запросил разбор",
  verdictGot: "получил разбор",
  paywall: "увидел экран оплаты",
  payStarted: "нажал купить",
  testerCode: "вошёл по коду тестировщика",
};

let sent = 0;

/**
 * Отправляет шаг. Молча и не мешая: аналитика не должна ни тормозить
 * приложение, ни ронять его, если сервер не отвечает.
 */
export function track(name, props = {}) {
  if (!isRemote || !name || sent >= 200) return;
  sent += 1;

  const row = {
    name,
    props,
    version: typeof __BUILD_TIME__ === "string" ? __BUILD_TIME__ : "",
  };

  // Без await: ждать ответа незачем, а ошибку глотаем — сбой аналитики
  // не должен превращаться в сбой продукта.
  supabase
    .from("events")
    .insert(row)
    .then(() => {})
    .catch(() => {});
}
