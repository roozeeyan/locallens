// Кто и что видит за деньги.
//
// Платит один — открывается обоим. Пара и есть единица покупки: смысл
// приложения в сравнении, поэтому доступ, открытый одному, бессмысленен.
// Отсюда одно правило на всё приложение: доступ есть, если купила я сама
// или если купил кто-то, с кем я связана.

/**
 * Режим теста: на время проверки на живых парах платный барьер только
 * мешает — он ломает то самое прохождение, которое мы и хотим увидеть.
 * Включается переменной VITE_OPEN_ALL=1 при сборке, в обычной сборке
 * ничего не меняет.
 */
export const OPEN_ALL = String(import.meta.env.VITE_OPEN_ALL || "") === "1";

/**
 * Первая версия обслуживает один набор обстоятельств: два человека,
 * которые проходят анкету вдвоём. Кандидаты, друзья и колоды никуда
 * не делись — они просто не показываются, пока мы смотрим за парами.
 * Выключается переменной VITE_PAIR_ONLY=0 при сборке.
 */
export const PAIR_ONLY = String(import.meta.env.VITE_PAIR_ONLY || "") !== "0";

/** Открыт ли доступ мне — своей покупкой или покупкой партнёра. */
export function hasAccess(profile, connections = []) {
  if (OPEN_ALL) return true;
  return Boolean(profile?.premium) || connections.some((x) => x.premium);
}

/** Имя того, кто оплатил за двоих. Пусто, если платила я сама. */
export function paidBy(profile, connections = []) {
  if (profile?.premium) return "";
  return connections.find((x) => x.premium)?.name || "";
}
